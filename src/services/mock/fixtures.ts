const DAY = 24 * 60 * 60 * 1000;

function iso(offsetDays: number, hour = 10, minute = 0): string {
  const d = new Date(Date.now() + offsetDays * DAY);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
}

